const assert=require('node:assert/strict');
const {validPreferences,dateAt,etMidnight,daysInZone,formatTime}=require('./site_ui.js');
assert.deepEqual(validPreferences(null),{language:'zh-Hant',timezone:'Asia/Taipei'});
assert.deepEqual(validPreferences({language:'bad',timezone:'bad'}),{language:'zh-Hant',timezone:'Asia/Taipei'});
assert.deepEqual(validPreferences({language:'en',timezone:'America/New_York'}),{language:'en',timezone:'America/New_York'});
assert.equal(formatTime('2027-01-01T02:30:00Z','Asia/Taipei'),'01/01 10:30');
assert.equal(formatTime('2027-01-01T02:30:00Z','America/New_York'),'12/31 21:30');
assert.equal(formatTime('2026-10-31T23:30:00Z','Asia/Taipei'),'11/01 07:30');
assert.equal(formatTime('2026-11-02T00:30:00Z','Asia/Taipei'),'11/02 08:30');
assert.equal(formatTime('2026-10-31T23:30:00Z','America/New_York'),'10/31 19:30');
assert.equal(formatTime('2026-11-02T00:30:00Z','America/New_York'),'11/01 19:30');
assert.equal(new Date(etMidnight('2026-11-01')).toISOString(),'2026-11-01T04:00:00.000Z');
assert.equal(new Date(etMidnight('2026-11-02')).toISOString(),'2026-11-02T05:00:00.000Z');
assert.equal(new Date(etMidnight('2027-03-14')).toISOString(),'2027-03-14T05:00:00.000Z');
assert.equal(new Date(etMidnight('2027-03-15')).toISOString(),'2027-03-15T04:00:00.000Z');
assert.deepEqual(daysInZone('2026-10-20','2026-10-25','Asia/Taipei'),['2026-10-20','2026-10-21','2026-10-22','2026-10-23','2026-10-24','2026-10-25','2026-10-26']);
assert.deepEqual(daysInZone('2026-10-20','2026-10-25','America/New_York'),['2026-10-20','2026-10-21','2026-10-22','2026-10-23','2026-10-24','2026-10-25']);
assert.equal(dateAt('2027-01-01T02:30:00Z','America/Los_Angeles'),'2026-12-31');
assert.equal(formatTime(null,'Asia/Taipei'),'時間待定');
console.log('Validated preferences, source UTC preservation, local dates, year boundaries, DST midnight/clock and scoring-period date spans passed');
